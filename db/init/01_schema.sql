-- ============================================================
-- Modelo dimensional OEE — esquema estrella/constelación
-- PostgreSQL 16
-- ============================================================
-- Capas:
--   oee   : modelo dimensional (dimensiones, hechos, vistas)
--   stg   : staging auditable (payload crudo redactado)
--   audit : bitácora de corridas, calidad y conciliación
-- ============================================================

CREATE SCHEMA IF NOT EXISTS oee;
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS audit;

-- ------------------------------------------------------------
-- DIMENSIONES
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS oee.dim_tiempo (
    tiempo_key        integer      PRIMARY KEY,
    fecha             date         NOT NULL UNIQUE,
    anio              smallint     NOT NULL,
    trimestre         smallint     NOT NULL,
    mes               smallint     NOT NULL,
    nombre_mes        varchar(20)  NOT NULL,
    dia               smallint     NOT NULL,
    dia_semana        smallint     NOT NULL,  -- ISO: 1=lunes ... 7=domingo
    nombre_dia        varchar(20)  NOT NULL,
    semana_iso        smallint     NOT NULL,
    anio_semana       varchar(8)   NOT NULL,  -- 2025-W13
    periodo_anio_mes  varchar(7)   NOT NULL,  -- 2025-03
    es_fin_semana     boolean      NOT NULL,
    es_festivo        boolean      NOT NULL DEFAULT false
);
COMMENT ON TABLE oee.dim_tiempo IS 'Dimensión calendario construida por el equipo. Grano: un día.';

CREATE TABLE IF NOT EXISTS oee.dim_maquina (
    maquina_key                 smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                      varchar(20) NOT NULL UNIQUE,
    nombre                      varchar(60) NOT NULL,
    factor_produccion_legacy    numeric(6,3),
    activa                      boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE oee.dim_maquina IS 'Líneas de envasado Vinilos_1..Vinilos_4.';

CREATE TABLE IF NOT EXISTS oee.dim_turno (
    turno_key       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          varchar(10) NOT NULL UNIQUE,
    nombre          varchar(60) NOT NULL,
    hora_inicio     time,
    hora_fin        time,
    duracion_horas  numeric(4,1),
    es_nocturno     boolean NOT NULL DEFAULT false,
    es_valido       boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE oee.dim_turno IS 'Turnos normalizados a partir del texto libre del Excel.';

CREATE TABLE IF NOT EXISTS oee.dim_referencia (
    referencia_key              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_natural          varchar(80) NOT NULL,
    nombre_normalizado          varchar(80) NOT NULL,
    num_colores                 smallint,
    unidades_por_display        integer,
    unidades_por_paca           integer,
    unidades_por_minuto_ideal   numeric(6,2) NOT NULL DEFAULT 72,
    vigente_desde               date NOT NULL DEFAULT DATE '1900-01-01',
    vigente_hasta               date NOT NULL DEFAULT DATE '9999-12-31',
    es_vigente                  boolean NOT NULL DEFAULT true,
    version                     smallint NOT NULL DEFAULT 1,
    origen                      varchar(30) NOT NULL DEFAULT 'CATALOGO',
    UNIQUE (referencia_natural, version)
);
COMMENT ON TABLE oee.dim_referencia IS
'Dimensión SCD Tipo 2. La conversión unidades/paca puede cambiar con el empaque;
se conserva la versión vigente al momento del hecho para no recalcular historia.';

CREATE TABLE IF NOT EXISTS oee.dim_operario (
    operario_key    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seudonimo       varchar(20) NOT NULL UNIQUE,
    nombre_hash     char(64) NOT NULL UNIQUE,
    activo          boolean NOT NULL DEFAULT true,
    es_valido       boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE oee.dim_operario IS
'Operarias seudonimizadas (SHA-256 con sal). No se almacena el nombre real.';

CREATE TABLE IF NOT EXISTS oee.dim_area (
    area_key    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      varchar(60) NOT NULL UNIQUE,
    tipo        varchar(30)
);
COMMENT ON TABLE oee.dim_area IS 'Área de impacto del paro: Mantenimiento, Producción, Calidad, etc.';

CREATE TABLE IF NOT EXISTS oee.dim_codigo_paro (
    codigo_key              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                  smallint NOT NULL UNIQUE,
    nombre                  varchar(150) NOT NULL,
    area_key                smallint REFERENCES oee.dim_area(area_key),
    categoria               varchar(30),
    es_programado           boolean NOT NULL DEFAULT false,
    documentado_pmto22      boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE oee.dim_codigo_paro IS 'Jerarquía nivel 1: códigos de paro 01..18 del P-MTO-22 y formato hora a hora.';

CREATE TABLE IF NOT EXISTS oee.dim_subcodigo_paro (
    subcodigo_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_key      smallint NOT NULL REFERENCES oee.dim_codigo_paro(codigo_key),
    subcodigo       varchar(20) NOT NULL,
    nombre          varchar(180) NOT NULL,
    nivel           smallint NOT NULL,
    subcodigo_padre varchar(20),
    ruta            varchar(60),
    es_estimado     boolean NOT NULL DEFAULT false,
    UNIQUE (codigo_key, subcodigo)
);
COMMENT ON TABLE oee.dim_subcodigo_paro IS
'Jerarquía nivel 2/3 (código -> subcódigo). Solo los códigos 1, 3 y 5 tienen
subcódigo en el formato; los demás usan el miembro SIN_ESP.';

CREATE TABLE IF NOT EXISTS oee.dim_personal (
    personal_key    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seudonimo       varchar(20) NOT NULL UNIQUE,
    nombre_hash     char(64) NOT NULL UNIQUE,
    area_key        smallint REFERENCES oee.dim_area(area_key),
    es_valido       boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE oee.dim_personal IS
'Personal de mantenimiento seudonimizado que intervino en un paro.';

-- ------------------------------------------------------------
-- HECHOS
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS oee.fact_produccion (
    produccion_key              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_key                  integer NOT NULL REFERENCES oee.dim_tiempo(tiempo_key),
    maquina_key                 smallint NOT NULL REFERENCES oee.dim_maquina(maquina_key),
    turno_key                   smallint NOT NULL REFERENCES oee.dim_turno(turno_key),
    referencia_key              integer NOT NULL REFERENCES oee.dim_referencia(referencia_key),
    operario_key                integer NOT NULL REFERENCES oee.dim_operario(operario_key),
    origen_fila                 integer NOT NULL,
    pacas_producidas            numeric(12,2) NOT NULL DEFAULT 0 CHECK (pacas_producidas >= 0),
    horas_trabajadas            numeric(8,2)  NOT NULL DEFAULT 0 CHECK (horas_trabajadas >= 0),
    horas_no_trabajadas_dia     numeric(8,2),
    unidades_producidas        numeric(14,2) CHECK (unidades_producidas >= 0),
    minutos_ideales             numeric(14,2) CHECK (minutos_ideales >= 0),
    tipo_paro_texto             varchar(200),
    observaciones               text,
    es_outlier                  boolean NOT NULL DEFAULT false,
    es_incompleto               boolean NOT NULL DEFAULT false,
    hash_origen                 char(64) NOT NULL,
    cargado_en                  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (origen_fila)
);
COMMENT ON TABLE oee.fact_produccion IS
'Grano: un registro de producción (una fila del Excel con pacas u horas).
No incluye los paros; esos viven en fact_paro para no duplicar magnitudes.';

CREATE TABLE IF NOT EXISTS oee.fact_paro (
    paro_key                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tiempo_key                  integer NOT NULL REFERENCES oee.dim_tiempo(tiempo_key),
    maquina_key                 smallint NOT NULL REFERENCES oee.dim_maquina(maquina_key),
    turno_key                   smallint NOT NULL REFERENCES oee.dim_turno(turno_key),
    referencia_key              integer NOT NULL REFERENCES oee.dim_referencia(referencia_key),
    operario_key                integer NOT NULL REFERENCES oee.dim_operario(operario_key),
    codigo_key                  smallint NOT NULL REFERENCES oee.dim_codigo_paro(codigo_key),
    subcodigo_key               integer NOT NULL REFERENCES oee.dim_subcodigo_paro(subcodigo_key),
    area_key                    smallint REFERENCES oee.dim_area(area_key),
    personal_key                integer REFERENCES oee.dim_personal(personal_key),
    origen_fila                 integer NOT NULL,
    origen_columna              smallint NOT NULL CHECK (origen_columna BETWEEN 1 AND 18),
    minutos_paro                numeric(10,2) NOT NULL CHECK (minutos_paro > 0),
    horas_paro                  numeric(12,8) NOT NULL CHECK (horas_paro > 0),
    area_involucrada_texto      varchar(60),
    tipo_paro_texto             varchar(200),
    observacion_paro            text,
    es_sin_produccion           boolean NOT NULL DEFAULT false,
    hash_origen                 char(64) NOT NULL,
    cargado_en                  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (origen_fila, origen_columna)
);
COMMENT ON TABLE oee.fact_paro IS
'Grano: un evento de paro = una fila de origen x una columna de código (1..18)
con minutos > 0. Se despivota el formato ancho del Excel.';

CREATE TABLE IF NOT EXISTS oee.fact_produccion_hora (
    hora_key            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_hora             timestamptz NOT NULL,
    tiempo_key          integer NOT NULL REFERENCES oee.dim_tiempo(tiempo_key),
    maquina_key         smallint NOT NULL REFERENCES oee.dim_maquina(maquina_key),
    turno_key           smallint NOT NULL REFERENCES oee.dim_turno(turno_key),
    referencia_key      integer NOT NULL REFERENCES oee.dim_referencia(referencia_key),
    pacas_producidas    numeric(10,2) NOT NULL DEFAULT 0,
    unidades_producidas numeric(14,2) NOT NULL DEFAULT 0,
    minutos_planificados numeric(6,2) NOT NULL DEFAULT 60,
    minutos_operacion   numeric(6,2) NOT NULL DEFAULT 0,
    minutos_paro        numeric(6,2) NOT NULL DEFAULT 0,
    origen              varchar(20) NOT NULL DEFAULT 'SIMULACION',
    UNIQUE (ts_hora, maquina_key)
);
COMMENT ON TABLE oee.fact_produccion_hora IS
'Hecho near real-time alimentado por el simulador (o, en producción, por el
colector MQTT/OPC UA). Grano: minuto/hora x máquina.';

