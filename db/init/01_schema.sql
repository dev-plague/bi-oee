-- Base día x máquina. Incluye TODOS los paros del día/máquina, aunque no
-- exista una fila de producción con el mismo turno (caso frecuente: las
-- filas hijas de paro tienen turno vacío). Guarda medidas aditivas.
CREATE OR REPLACE VIEW oee.vw_oee_base_dia AS
WITH prod AS (
    SELECT
        p.tiempo_key,
        p.maquina_key,
        SUM(p.horas_trabajadas)                                              AS horas_trabajadas,
        SUM(p.horas_trabajadas) FILTER (WHERE p.minutos_ideales IS NOT NULL) AS horas_trabajadas_ref,
        SUM(p.pacas_producidas)                                              AS pacas,
        SUM(p.unidades_producidas)                                           AS unidades_producidas,
        SUM(p.minutos_ideales)                                               AS minutos_ideales,
        COUNT(*)                                                             AS registros_produccion
    FROM oee.fact_produccion p
    GROUP BY 1, 2
),
paro AS (
    SELECT
        f.tiempo_key,
        f.maquina_key,
        SUM(f.horas_paro)                                                    AS horas_paro,
        COUNT(*)                                                             AS eventos_paro,
        COUNT(*) FILTER (WHERE c.es_programado = false)                      AS fallas,
        SUM(f.horas_paro) FILTER (WHERE c.es_programado = false)             AS horas_paro_no_programado
    FROM oee.fact_paro f
    JOIN oee.dim_codigo_paro c ON c.codigo_key = f.codigo_key
    GROUP BY 1, 2
),
base AS (
    SELECT
        COALESCE(p.tiempo_key, q.tiempo_key)                                  AS tiempo_key,
        COALESCE(p.maquina_key, q.maquina_key)                                AS maquina_key,
        COALESCE(p.horas_trabajadas, 0)                                       AS horas_trabajadas,
        COALESCE(q.horas_paro, 0)                                             AS horas_paro,
        GREATEST(COALESCE(p.horas_trabajadas, 0) - COALESCE(q.horas_paro, 0), 0) AS horas_operativas,
        COALESCE(p.horas_trabajadas_ref, 0)                                   AS horas_trabajadas_ref,
        CASE WHEN COALESCE(p.horas_trabajadas, 0) > 0
             THEN COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                  / p.horas_trabajadas
             ELSE 0 END                                                       AS horas_paro_ref,
        CASE WHEN COALESCE(p.horas_trabajadas, 0) > 0
             THEN GREATEST(COALESCE(p.horas_trabajadas_ref, 0)
                  - COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                    / p.horas_trabajadas, 0)
             ELSE 0 END                                                       AS horas_operativas_ref,
        COALESCE(p.pacas, 0)                                                  AS pacas,
        COALESCE(p.unidades_producidas, 0)                                    AS unidades_producidas,
        COALESCE(p.minutos_ideales, 0)                                        AS minutos_ideales,
        CASE WHEN COALESCE(p.horas_trabajadas_ref, 0) > 0
             THEN COALESCE(p.minutos_ideales, 0)
                  * GREATEST(COALESCE(p.horas_trabajadas_ref, 0)
                    - COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                      / p.horas_trabajadas, 0)
                  / p.horas_trabajadas_ref
             ELSE NULL END                                                    AS minutos_ideales_operativos,
        COALESCE(q.eventos_paro, 0)                                           AS eventos_paro,
        COALESCE(q.fallas, 0)                                                 AS fallas,
        COALESCE(q.horas_paro_no_programado, 0)                               AS horas_paro_no_programado,
        COALESCE(p.registros_produccion, 0)                                   AS registros_produccion
    FROM prod p
    FULL OUTER JOIN paro q
           ON q.tiempo_key = p.tiempo_key
          AND q.maquina_key = p.maquina_key
)
SELECT
    b.tiempo_key,
    t.fecha,
    t.anio,
    t.mes,
    t.periodo_anio_mes,
    b.maquina_key,
    m.codigo                                                        AS maquina,
    b.horas_trabajadas,
    b.horas_paro,
    b.horas_operativas,
    b.horas_trabajadas_ref,
    b.horas_paro_ref,
    b.horas_operativas_ref,
    b.pacas,
    b.unidades_producidas,
    b.minutos_ideales,
    b.minutos_ideales_operativos,
    b.eventos_paro,
    b.fallas,
    b.horas_paro_no_programado,
    b.registros_produccion,
    CASE WHEN b.horas_trabajadas > 0
         THEN b.horas_trabajadas_ref / b.horas_trabajadas END        AS cobertura_referencia
FROM base b
JOIN oee.dim_tiempo t  ON t.tiempo_key = b.tiempo_key
JOIN oee.dim_maquina m ON m.maquina_key = b.maquina_key;

-- Día x máquina: ratios de OEE listos para Power BI/Grafana.
CREATE OR REPLACE VIEW oee.vw_oee_diario_maquina AS
SELECT
    tiempo_key,
    fecha,
    anio,
    mes,
    periodo_anio_mes,
    maquina_key,
    maquina,
    horas_trabajadas,
    horas_paro,
    horas_operativas,
    horas_trabajadas_ref,
    horas_paro_ref,
    horas_operativas_ref,
    pacas,
    unidades_producidas,
    minutos_ideales,
    minutos_ideales_operativos,
    eventos_paro,
    fallas,
    horas_paro_no_programado,
    registros_produccion,
    cobertura_referencia,
    CASE WHEN horas_trabajadas > 0
         THEN horas_operativas / horas_trabajadas END                 AS disponibilidad_total,
    CASE WHEN horas_trabajadas_ref > 0
         THEN horas_operativas_ref / horas_trabajadas_ref END         AS disponibilidad,
    CASE WHEN minutos_ideales_operativos > 0
         THEN LEAST(unidades_producidas / minutos_ideales_operativos, 1.0) END AS rendimiento,
    CASE WHEN minutos_ideales_operativos > 0
         THEN unidades_producidas / minutos_ideales_operativos END    AS rendimiento_calculado,
    1.0::numeric                                                     AS calidad,
    CASE WHEN minutos_ideales > 0
         THEN unidades_producidas / minutos_ideales END              AS oee_calculado,
    CASE WHEN horas_trabajadas_ref > 0
              AND minutos_ideales_operativos > 0
         THEN (horas_operativas_ref / horas_trabajadas_ref)
              * LEAST(unidades_producidas / minutos_ideales_operativos, 1.0)
    END                                                              AS oee
FROM oee.vw_oee_base_dia;

-- Mes x máquina.
CREATE OR REPLACE VIEW oee.vw_oee_mensual_maquina AS
SELECT
    anio,
    mes,
    periodo_anio_mes,
    maquina_key,
    maquina,
    SUM(horas_trabajadas)                                               AS horas_trabajadas,
    SUM(horas_paro)                                                     AS horas_paro,
    SUM(horas_operativas)                                               AS horas_operativas,
    SUM(horas_trabajadas_ref)                                           AS horas_trabajadas_ref,
    SUM(horas_operativas_ref)                                           AS horas_operativas_ref,
    SUM(pacas)                                                          AS pacas,
    SUM(unidades_producidas)                                            AS unidades_producidas,
    SUM(minutos_ideales)                                                AS minutos_ideales,
    SUM(minutos_ideales_operativos)                                     AS minutos_ideales_operativos,
    SUM(eventos_paro)                                                   AS eventos_paro,
    SUM(fallas)                                                         AS fallas,
    SUM(horas_paro_no_programado)                                       AS horas_paro_no_programado,
    CASE WHEN SUM(horas_trabajadas) > 0
         THEN SUM(horas_trabajadas_ref) / SUM(horas_trabajadas) END     AS cobertura_referencia,
    CASE WHEN SUM(horas_trabajadas) > 0
         THEN SUM(horas_operativas) / SUM(horas_trabajadas) END         AS disponibilidad_total,
    CASE WHEN SUM(horas_trabajadas_ref) > 0
         THEN SUM(horas_operativas_ref) / SUM(horas_trabajadas_ref) END AS disponibilidad,
    CASE WHEN SUM(minutos_ideales_operativos) > 0
         THEN LEAST(SUM(unidades_producidas) / SUM(minutos_ideales_operativos), 1.0) END AS rendimiento,
    1.0::numeric                                                        AS calidad,
    CASE WHEN SUM(horas_trabajadas_ref) > 0
              AND SUM(minutos_ideales_operativos) > 0
         THEN (SUM(horas_operativas_ref) / SUM(horas_trabajadas_ref))
              * LEAST(SUM(unidades_producidas) / SUM(minutos_ideales_operativos), 1.0)
    END                                                                 AS oee
FROM oee.vw_oee_diario_maquina
GROUP BY anio, mes, periodo_anio_mes, maquina_key, maquina;

-- Base día x máquina x turno. Se usa solo para el análisis por turno;
-- los paros con turno vacío quedan en el miembro SD y no se imputan.
CREATE OR REPLACE VIEW oee.vw_oee_base_turno AS
WITH prod AS (
    SELECT
        p.tiempo_key,
        p.maquina_key,
        p.turno_key,
        SUM(p.horas_trabajadas)                                              AS horas_trabajadas,
        SUM(p.horas_trabajadas) FILTER (WHERE p.minutos_ideales IS NOT NULL) AS horas_trabajadas_ref,
        SUM(p.pacas_producidas)                                              AS pacas,
        SUM(p.unidades_producidas)                                           AS unidades_producidas,
        SUM(p.minutos_ideales)                                               AS minutos_ideales,
        COUNT(*)                                                             AS registros_produccion
    FROM oee.fact_produccion p
    GROUP BY 1, 2, 3
),
paro AS (
    SELECT
        f.tiempo_key,
        f.maquina_key,
        f.turno_key,
        SUM(f.horas_paro)                                                    AS horas_paro,
        COUNT(*)                                                             AS eventos_paro,
        COUNT(*) FILTER (WHERE c.es_programado = false)                      AS fallas,
        SUM(f.horas_paro) FILTER (WHERE c.es_programado = false)             AS horas_paro_no_programado
    FROM oee.fact_paro f
    JOIN oee.dim_codigo_paro c ON c.codigo_key = f.codigo_key
    GROUP BY 1, 2, 3
),
base AS (
    SELECT
        COALESCE(p.tiempo_key, q.tiempo_key)                                  AS tiempo_key,
        COALESCE(p.maquina_key, q.maquina_key)                                AS maquina_key,
        COALESCE(p.turno_key, q.turno_key)                                    AS turno_key,
        COALESCE(p.horas_trabajadas, 0)                                       AS horas_trabajadas,
        COALESCE(q.horas_paro, 0)                                             AS horas_paro,
        GREATEST(COALESCE(p.horas_trabajadas, 0) - COALESCE(q.horas_paro, 0), 0) AS horas_operativas,
        COALESCE(p.horas_trabajadas_ref, 0)                                   AS horas_trabajadas_ref,
        CASE WHEN COALESCE(p.horas_trabajadas, 0) > 0
             THEN COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                  / p.horas_trabajadas
             ELSE 0 END                                                       AS horas_paro_ref,
        CASE WHEN COALESCE(p.horas_trabajadas, 0) > 0
             THEN GREATEST(COALESCE(p.horas_trabajadas_ref, 0)
                  - COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                    / p.horas_trabajadas, 0)
             ELSE 0 END                                                       AS horas_operativas_ref,
        COALESCE(p.pacas, 0)                                                  AS pacas,
        COALESCE(p.unidades_producidas, 0)                                    AS unidades_producidas,
        COALESCE(p.minutos_ideales, 0)                                        AS minutos_ideales,
        CASE WHEN COALESCE(p.horas_trabajadas_ref, 0) > 0
             THEN COALESCE(p.minutos_ideales, 0)
                  * GREATEST(COALESCE(p.horas_trabajadas_ref, 0)
                    - COALESCE(q.horas_paro, 0) * COALESCE(p.horas_trabajadas_ref, 0)
                      / p.horas_trabajadas, 0)
                  / p.horas_trabajadas_ref
             ELSE NULL END                                                    AS minutos_ideales_operativos,
        COALESCE(q.eventos_paro, 0)                                           AS eventos_paro,
        COALESCE(q.fallas, 0)                                                 AS fallas,
        COALESCE(q.horas_paro_no_programado, 0)                               AS horas_paro_no_programado,
        COALESCE(p.registros_produccion, 0)                                   AS registros_produccion
    FROM prod p
    FULL OUTER JOIN paro q
           ON q.tiempo_key = p.tiempo_key
          AND q.maquina_key = p.maquina_key
          AND q.turno_key = p.turno_key
)
SELECT
    b.tiempo_key,
    t.fecha,
    t.anio,
    t.mes,
    t.periodo_anio_mes,
    b.maquina_key,
    m.codigo                                                        AS maquina,
    b.turno_key,
    tu.codigo                                                       AS turno,
    b.horas_trabajadas,
    b.horas_paro,
    b.horas_operativas,
    b.horas_trabajadas_ref,
    b.horas_operativas_ref,
    b.pacas,
    b.unidades_producidas,
    b.minutos_ideales,
    b.minutos_ideales_operativos,
    b.eventos_paro,
    b.fallas,
    b.horas_paro_no_programado,
    b.registros_produccion
FROM base b
JOIN oee.dim_tiempo t  ON t.tiempo_key = b.tiempo_key
JOIN oee.dim_maquina m ON m.maquina_key = b.maquina_key
JOIN oee.dim_turno tu  ON tu.turno_key = b.turno_key;

-- Turno (mes x turno, todas las máquinas).
CREATE OR REPLACE VIEW oee.vw_oee_turno AS
SELECT
    anio,
    mes,
    periodo_anio_mes,
    turno_key,
    turno,
    SUM(horas_trabajadas)                                               AS horas_trabajadas,
    SUM(horas_paro)                                                     AS horas_paro,
    SUM(horas_operativas)                                               AS horas_operativas,
    SUM(horas_trabajadas_ref)                                           AS horas_trabajadas_ref,
    SUM(horas_operativas_ref)                                           AS horas_operativas_ref,
    SUM(pacas)                                                          AS pacas,
    SUM(unidades_producidas)                                            AS unidades_producidas,
    SUM(minutos_ideales)                                                AS minutos_ideales,
    SUM(minutos_ideales_operativos)                                     AS minutos_ideales_operativos,
    SUM(eventos_paro)                                                   AS eventos_paro,
    SUM(fallas)                                                         AS fallas,
    CASE WHEN SUM(horas_trabajadas) > 0
         THEN SUM(horas_operativas) / SUM(horas_trabajadas) END         AS disponibilidad_total,
    CASE WHEN SUM(horas_trabajadas_ref) > 0
         THEN SUM(horas_operativas_ref) / SUM(horas_trabajadas_ref) END AS disponibilidad,
    CASE WHEN SUM(minutos_ideales_operativos) > 0
         THEN LEAST(SUM(unidades_producidas) / SUM(minutos_ideales_operativos), 1.0) END AS rendimiento,
    1.0::numeric                                                        AS calidad,
    CASE WHEN SUM(horas_trabajadas_ref) > 0
              AND SUM(minutos_ideales_operativos) > 0
         THEN (SUM(horas_operativas_ref) / SUM(horas_trabajadas_ref))
              * LEAST(SUM(unidades_producidas) / SUM(minutos_ideales_operativos), 1.0)
    END                                                                 AS oee
FROM oee.vw_oee_base_turno
GROUP BY anio, mes, periodo_anio_mes, turno_key, turno;

-- Pareto de paros por mes/máquina/código/subcódigo con % acumulado.
CREATE OR REPLACE VIEW oee.vw_pareto_paros AS
WITH base AS (
    SELECT
        t.anio,
        t.mes,
        t.periodo_anio_mes,
        f.maquina_key,
        m.codigo                    AS maquina,
        f.codigo_key,
        c.codigo,
        c.nombre                    AS causa,
        c.es_programado,
        f.subcodigo_key,
        s.subcodigo,
        s.nombre                    AS subcausa,
        SUM(f.horas_paro)           AS horas_paro,
        COUNT(*)                    AS eventos
    FROM oee.fact_paro f
    JOIN oee.dim_tiempo t          ON t.tiempo_key = f.tiempo_key
    JOIN oee.dim_maquina m         ON m.maquina_key = f.maquina_key
    JOIN oee.dim_codigo_paro c     ON c.codigo_key = f.codigo_key
    JOIN oee.dim_subcodigo_paro s  ON s.subcodigo_key = f.subcodigo_key
    GROUP BY t.anio, t.mes, t.periodo_anio_mes, f.maquina_key, m.codigo,
             f.codigo_key, c.codigo, c.nombre, c.es_programado,
             f.subcodigo_key, s.subcodigo, s.nombre
),
ranked AS (
    SELECT
        *,
        SUM(horas_paro) OVER (
            PARTITION BY anio, mes, maquina_key
            ORDER BY horas_paro DESC, codigo, subcodigo
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS horas_acumuladas,
        SUM(horas_paro) OVER (PARTITION BY anio, mes, maquina_key) AS horas_totales,
        ROW_NUMBER() OVER (
            PARTITION BY anio, mes, maquina_key
            ORDER BY horas_paro DESC, codigo, subcodigo
        ) AS ranking
    FROM base
)
SELECT
    *,
    CASE WHEN horas_totales > 0 THEN horas_paro / horas_totales END       AS porcentaje,
    CASE WHEN horas_totales > 0 THEN horas_acumuladas / horas_totales END  AS porcentaje_acumulado
FROM ranked;

-- MTBF / MTTR por día x máquina (solo fallas no programadas).
CREATE OR REPLACE VIEW oee.vw_mtbf_mttr AS
WITH prod AS (
    SELECT
        tiempo_key,
        maquina_key,
        SUM(horas_operativas) AS horas_operativas
    FROM oee.vw_oee_base_dia
    GROUP BY 1, 2
),
fallas AS (
    SELECT
        f.tiempo_key,
        f.maquina_key,
        COUNT(*)                                             AS fallas,
        SUM(f.horas_paro)                                    AS horas_paro_no_programado
    FROM oee.fact_paro f
    JOIN oee.dim_codigo_paro c ON c.codigo_key = f.codigo_key
    WHERE c.es_programado = false
    GROUP BY 1, 2
)
SELECT
    t.fecha,
    t.anio,
    t.mes,
    m.codigo                                              AS maquina,
    p.maquina_key,
    COALESCE(p.horas_operativas, 0)                       AS horas_operativas,
    COALESCE(f.fallas, 0)                                 AS fallas,
    COALESCE(f.horas_paro_no_programado, 0)               AS horas_paro_no_programado,
    CASE WHEN COALESCE(f.fallas, 0) > 0
         THEN p.horas_operativas / f.fallas END           AS mtbf_horas,
    CASE WHEN COALESCE(f.fallas, 0) > 0
         THEN f.horas_paro_no_programado / f.fallas END   AS mttr_horas
FROM prod p
JOIN oee.dim_tiempo t  ON t.tiempo_key = p.tiempo_key
JOIN oee.dim_maquina m ON m.maquina_key = p.maquina_key
LEFT JOIN fallas f     ON f.tiempo_key = p.tiempo_key AND f.maquina_key = p.maquina_key;

-- Estado actual (últimos 15 minutos simulados) por máquina.
CREATE OR REPLACE VIEW oee.vw_estado_actual_maquina AS
WITH ult AS (
    SELECT maquina_key, MAX(ts_hora) AS ultima_hora
    FROM oee.fact_produccion_hora
    GROUP BY maquina_key
),
ventana AS (
    SELECT f.*
    FROM oee.fact_produccion_hora f
    JOIN ult u ON u.maquina_key = f.maquina_key
    WHERE f.ts_hora >= u.ultima_hora - INTERVAL '15 minutes'
)
SELECT
    m.codigo                                                AS maquina,
    MAX(v.ts_hora)                                          AS ultima_actualizacion,
    SUM(v.unidades_producidas)                              AS unidades,
    SUM(v.minutos_planificados)                             AS minutos_planificados,
    SUM(v.minutos_operacion)                                AS minutos_operacion,
    SUM(v.minutos_paro)                                     AS minutos_paro,
    SUM(v.minutos_operacion) / NULLIF(SUM(v.minutos_planificados), 0) AS disponibilidad,
    SUM(v.unidades_producidas) / NULLIF(SUM(v.minutos_operacion) * 72, 0) AS rendimiento,
    SUM(v.unidades_producidas) / NULLIF(SUM(v.minutos_planificados) * 72, 0) AS oee,
    CASE WHEN SUM(v.minutos_paro) > 30 THEN 'PARO'
         WHEN SUM(v.unidades_producidas) / NULLIF(SUM(v.minutos_planificados) * 72, 0) < 0.60 THEN 'ALERTA'
         ELSE 'OK' END                                      AS estado
FROM ventana v
JOIN oee.dim_maquina m ON m.maquina_key = v.maquina_key
GROUP BY m.codigo;

-- Serie por minuto para Grafana.
CREATE OR REPLACE VIEW oee.vw_oee_hora AS
SELECT
    date_trunc('minute', f.ts_hora)                         AS hora,
    m.codigo                                                AS maquina,
    SUM(f.unidades_producidas)                              AS unidades,
    SUM(f.minutos_planificados)                             AS minutos_planificados,
    SUM(f.minutos_operacion)                                AS minutos_operacion,
    SUM(f.minutos_paro)                                     AS minutos_paro,
    SUM(f.minutos_operacion) / NULLIF(SUM(f.minutos_planificados), 0) AS disponibilidad,
    SUM(f.unidades_producidas) / NULLIF(SUM(f.minutos_operacion) * 72, 0) AS rendimiento,
    SUM(f.unidades_producidas) / NULLIF(SUM(f.minutos_planificados) * 72, 0) AS oee
FROM oee.fact_produccion_hora f
JOIN oee.dim_maquina m ON m.maquina_key = f.maquina_key
GROUP BY 1, 2;

